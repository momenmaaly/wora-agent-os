/** node:test's spec reporter (Node 22+) prints `ℹ pass N` / `ℹ fail N`; TAP prints `# pass N`. */
export function testsPassed(output: string): boolean {
  const pass = /(?:^|\n)\s*(?:ℹ|#)\s*pass\s+(\d+)/iu.exec(output)?.[1] ?? /tests\s+(\d+)\s+passed/iu.exec(output)?.[1];
  const fail = /(?:^|\n)\s*(?:ℹ|#)\s*fail\s+(\d+)/iu.exec(output)?.[1] ?? /#\s*fail\s+(\d+)/iu.exec(output)?.[1];
  return Boolean(pass && Number(pass) > 0 && (!fail || Number(fail) === 0));
}

