const scaffoldSchema = z.object({
  name: z.string().min(1).max(80).regex(/^[A-Za-z0-9][A-Za-z0-9 _-]*$/, 'letters, digits, space, dash, underscore'),
  brief: z.string().max(2000).optional(),
}).strict();

export const scaffoldWebappTool: ToolDefinition = {
  id: 'scaffold.webapp',
  name: 'Scaffold Working Web App',
  description: 'Generates a complete zero-dependency web application (static UI + Node http JSON API + node:test suite) into the sandboxed workspace and executes the test suite. Returns the file list and the real test output as evidence.',
  inputSchema: { type: 'object', properties: { name: { type: 'string' }, brief: { type: 'string' } }, required: ['name'], additionalProperties: false },
  schema: scaffoldSchema,
  permission: 'workspace:write',
  risk: 'medium',
  environment: 'host',
  timeoutMs: 45_000,
  async execute(input: z.infer<typeof scaffoldSchema>, ctx) {
    const appDir = resolveInWorkspace(ctx.workspaceId, path.join('apps', input.name.replace(/\s+/g, '-').toLowerCase()));
    for (const [rel, content] of Object.entries(APP_FILES)) {
      const target = path.join(appDir, rel);
      mkdirSync(path.dirname(target), { recursive: true });
      const opened = openWorkspaceFile(ctx.workspaceId, path.relative(workspacePath(ctx.workspaceId), target), 'write');
      try { writeFileSync(opened.fd, content, 'utf8'); } finally { closeSync(opened.fd); }
    }
    const written = Object.keys(APP_FILES).map((rel) => path.join('apps', input.name.replace(/\s+/g, '-').toLowerCase(), rel));

    let testOutput = '';
    let testPassed = false;
    try {
      const { stdout, stderr } = await execFileAsync(process.execPath, ['--test', 'test/app.test.mjs'], {
        cwd: appDir,
        timeout: 30_000,
        maxBuffer: 1024 * 1024,
        env: { PATH: process.env.PATH, NODE_ENV: 'test' },
      });
      testOutput = `${stdout}${stderr}`.trim();
      testPassed = testsPassed(testOutput);
    } catch (err) {
      const e = err as { stdout?: string; stderr?: string; message?: string };
      testOutput = `${e.stdout ?? ''}${e.stderr ?? ''}${e.message ?? ''}`.trim();
      testPassed = false;
    }

    return {
      appPath: path.relative(workspacePath(ctx.workspaceId), appDir),
      absolutePath: appDir,
      files: written,
      runCommand: `PORT=4173 node ${path.join(appDir, 'server.mjs')}`,
      testCommand: 'node --test test/app.test.mjs',
      testPassed,
      testOutput: testOutput.slice(0, 4000),
      brief: input.brief ?? null,
    };
  },
};

const hostExecSchema = z.object({
  command: z.literal('node'),
  args: z.array(z.string().min(1).max(300)).min(2).max(10),
  cwd: z.string().max(500).optional(),
}).strict();

export const hostExecTool: ToolDefinition = {
  id: 'host.exec',
  name: 'Run Node Test (allowlisted)',
  description: 'Executes exactly `node --test <path>` inside the sandboxed workspace. No other commands, flags or paths are permitted.',
  inputSchema: { type: 'object', properties: { command: { const: 'node' }, args: { type: 'array', items: { type: 'string' } }, cwd: { type: 'string' } }, required: ['command', 'args'], additionalProperties: false },
  schema: hostExecSchema,
  permission: 'host:exec',
  risk: 'high',
  environment: 'host',
  timeoutMs: 45_000,
  async execute(input: z.infer<typeof hostExecSchema>, ctx) {
    if (input.command !== 'node') throw new Error('Only `node` is allowlisted');
    const args = input.args;
    if (args[0] !== '--test') throw new Error('Only `node --test` is allowlisted');
    const cwd = resolveInWorkspace(ctx.workspaceId, input.cwd ?? '.');
    for (const arg of args.slice(1)) {
      if (arg.startsWith('-')) throw new Error(`Flag "${arg}" is not allowlisted`);
      resolveInWorkspace(ctx.workspaceId, path.join(input.cwd ?? '.', arg));
    }
    const workspaceRoot = workspacePath(ctx.workspaceId);
    // Node's permission model is the available OS-level boundary here: the test
    // process may read/write only the workspace and cannot spawn child processes
    // or load addons. Network access is not restricted by Node permissions; a
    // container/network namespace is still required for that guarantee.
    const nodeArgs = [
      '--permission',
      `--allow-fs-read=${workspaceRoot}`,
      `--allow-fs-write=${workspaceRoot}`,
      // Node 22 reserves a large Wasm address space for undici's HTTP parser;
      // the trap-handler variant exceeds the 2 GB resource cap.
      '--disable-wasm-trap-handler',
      // Node 22 only exposes the experimental spelling; Node 24 accepts both.
      '--test', '--experimental-test-isolation=none', ...args.slice(1),
    ];
    // Node 22 reserves a ~4 GB V8 pointer-compression cage; 2 GB makes the
    // test process fail intermittently under parallel CI load.
    const launch = resourceLimitedCommand(process.execPath, nodeArgs, { addressSpaceBytes: 6 * 1024 * 1024 * 1024 });
    const { stdout, stderr } = await execFileAsync(launch.command, launch.args, {
      cwd,
      timeout: 30_000,
      maxBuffer: 1024 * 1024,
      env: { PATH: process.env.PATH, NODE_ENV: 'test', HOME: process.env.HOME, TMPDIR: process.env.TMPDIR },
    });
    const output = `${stdout}${stderr}`.trim();
    const passed = testsPassed(output);
    return {
      cwd: path.relative(workspaceRoot, cwd), output: output.slice(0, 4000), passed,
      isolation: { mode: 'node-permission-model', filesystem: 'workspace-only', childProcesses: 'denied', network: 'not-restricted', resourceLimits: launch.isolation },
    };
  },
};
